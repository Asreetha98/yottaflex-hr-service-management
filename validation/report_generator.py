"""Run all validation checks and write the markdown reports.

    python -m validation.report_generator --input generator/output --output reports/DATA_VALIDATION_REPORT.md
    python -m validation.report_generator --reproducibility reports/REPRODUCIBILITY_REPORT.md

Exit code is non-zero when an *unintended* critical/high failure exists, or an injected anomaly was missed.
"""

import argparse
import json
import os
import sys
from collections import Counter
from typing import Any, Dict, List

import generator  # noqa: F401
from generator import config
from validation.business_rule_checks import run_business_checks
from validation.integrity_checks import load_tables, run_integrity_checks

EXPECTED_FULL = {"tickets": 5000, "messages": 20000, "knowledge_articles": 150, "policy_documents": 24}
# Behaviours of the ticket simulator itself (not injected): open tickets that outlived their SLA, and
# naturally ambiguous tickets closed without a clarification round. Reported separately, never hidden.
ORGANIC_CHECKS = ("open_sla_breach", "ambiguity_clarified")


def classify(findings: List[Dict[str, Any]], register: List[Dict[str, Any]]) -> Dict[str, Any]:
    keys = {(a["anomaly_type"], a["entity_id"]) for a in register}
    tickets = {(a["anomaly_type"], a["ticket_id"]) for a in register if a["ticket_id"]}
    injected, unintended, organic = [], [], []
    detected = set()
    for f in findings:
        atype = f["anomaly_type"]
        if atype and ((atype, f["entity_id"]) in keys or (atype, f["ticket_id"]) in tickets):
            injected.append(f)
            detected.add((atype, f["entity_id"]))
            detected.add((atype, f["ticket_id"]))
        elif f["check"] in ORGANIC_CHECKS:
            organic.append(f)
        else:
            unintended.append(f)
    missed = [a for a in register if (a["anomaly_type"], a["entity_id"]) not in detected
              and (a["anomaly_type"], a["ticket_id"]) not in detected]
    return {"injected": injected, "unintended": unintended, "organic": organic, "missed": missed}


def validate(directory: str, expected: Dict[str, int]) -> Dict[str, Any]:
    tables = load_tables(directory)
    with open(os.path.join(directory, "ground_truth.json"), "r", encoding="utf-8") as handle:
        register = json.load(handle)["anomalies"]
    findings = run_integrity_checks(tables, expected) + run_business_checks(tables)
    result = classify(findings, register)
    result.update({"register": register, "counts": {t: len(r) for t, r in tables.items()}})
    result["passed"] = not result["missed"] and not any(
        f["severity"] in ("CRITICAL", "HIGH") for f in result["unintended"])
    return result


def render(result: Dict[str, Any]) -> str:
    reg = result["register"]
    lines = ["# Data Validation Report", "",
             "Generated by `python -m validation.report_generator` (seed %d, reference date 2026-10-22)." % config.SEED, "",
             "## Summary", "",
             "| Item | Value |", "|---|---|",
             "| Overall result | **%s** |" % ("PASS" if result["passed"] else "FAIL"),
             "| Injected anomalies in register | %d |" % len(reg),
             "| Findings matching an injected anomaly (expected) | %d |" % len(result["injected"]),
             "| Injected anomalies NOT detected | %d |" % len(result["missed"]),
             "| Organic simulator findings (not injected, informational) | %d |" % len(result["organic"]),
             "| Unintended findings | %d |" % len(result["unintended"]), "",
             "## Row counts", "", "| Table | Rows |", "|---|---|"]
    lines += ["| %s | %d |" % (t, n) for t, n in result["counts"].items()]
    lines += ["", "## Injected anomalies: detection by type", "",
              "| Anomaly type | Injected | Detected by validators | Mandatory |", "|---|---|---|---|"]
    miss = Counter(a["anomaly_type"] for a in result["missed"])
    inj = Counter(a["anomaly_type"] for a in reg)
    mand = {a["anomaly_type"]: a["mandatory"] for a in reg}
    for atype in sorted(inj):
        lines.append("| %s | %d | %s | %s |" % (atype, inj[atype], "all" if not miss[atype] else
                                                 "%d missed" % miss[atype], "yes" if mand[atype] else "no"))
    lines += ["", "Note: validators may report more than one finding for a single injected anomaly, "
              "so finding counts can exceed the injected count.", "",
              "## Unintended findings (real data defects)", ""]
    if result["unintended"]:
        lines += ["| Check | Severity | Entity | Message |", "|---|---|---|---|"]
        lines += ["| %s | %s | %s %s | %s |" % (f["check"], f["severity"], f["entity_type"], f["entity_id"], f["message"])
                  for f in result["unintended"][:100]]
        if len(result["unintended"]) > 100:
            lines.append("\n_%d further findings omitted._" % (len(result["unintended"]) - 100))
    else:
        lines.append("None.")
    lines += ["", "## Injected anomaly register", "",
              "| Issue | Type | Entity | Severity |", "|---|---|---|---|"]
    lines += ["| %s | %s | %s %s | %s |" % (a["issue_id"], a["anomaly_type"], a["entity_type"], a["entity_id"], a["severity"])
              for a in reg]
    return "\n".join(lines) + "\n"


def render_repro(result: Dict[str, Any]) -> str:
    lines = ["# Reproducibility Report", "",
             "Method: the full dataset was generated twice with seed %d into separate temporary folders and the "
             "row count and SHA-256 of every output file were compared (`validation/reproducibility_checks.py`)." % config.SEED,
             "", "**Result: %s**" % ("IDENTICAL - all files match" if result["all_identical"] else "DIFFERENCES FOUND"), "",
             "| File | Rows run 1 | Rows run 2 | SHA-256 (run 1) | Match |", "|---|---|---|---|---|"]
    lines += ["| %s | %s | %s | `%s` | %s |" % (r["file"], r["rows_run1"], r["rows_run2"], r["sha256_run1"][:16] + "...",
                                               "yes" if r["identical"] else "NO") for r in result["files"]]
    return "\n".join(lines) + "\n"


def main(argv: Any = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", default=config.DEFAULT_OUTPUT_DIR)
    parser.add_argument("--output", default="reports/DATA_VALIDATION_REPORT.md")
    parser.add_argument("--reproducibility", default=None, help="also run the two-run check and write this file")
    parser.add_argument("--starter", action="store_true", help="skip the full-size row-count expectations")
    args = parser.parse_args(argv)
    code = 0
    result = validate(args.input, {} if args.starter else EXPECTED_FULL)
    os.makedirs(os.path.dirname(os.path.abspath(args.output)), exist_ok=True)
    with open(args.output, "w", encoding="utf-8") as handle:
        handle.write(render(result))
    print("validation: %s (injected findings=%d, missed=%d, unintended=%d, organic=%d)" % (
        "PASS" if result["passed"] else "FAIL", len(result["injected"]), len(result["missed"]),
        len(result["unintended"]), len(result["organic"])))
    if not result["passed"]:
        code = 1
    if args.reproducibility:
        from validation.reproducibility_checks import run_reproducibility_check
        repro = run_reproducibility_check()
        with open(args.reproducibility, "w", encoding="utf-8") as handle:
            handle.write(render_repro(repro))
        print("reproducibility: %s" % ("IDENTICAL" if repro["all_identical"] else "DIFFERENT"))
        if not repro["all_identical"]:
            code = 1
    return code


if __name__ == "__main__":
    sys.exit(main())
